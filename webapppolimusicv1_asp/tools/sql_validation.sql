PRINT '--- 17. Conteos del panel de administracion ---';
SELECT
    (SELECT COUNT(*) FROM TBL_SONG)     AS CANCIONES,
    (SELECT COUNT(*) FROM TBL_ARTIST)   AS ARTISTAS,
    (SELECT COUNT(*) FROM TBL_ALBUM)    AS ALBUMES,
    (SELECT COUNT(*) FROM TBL_USER)     AS USUARIOS,
    (SELECT COUNT(*) FROM TBL_USER WHERE USER_TYPE = 1) AS ADMINS,
    (SELECT COUNT(*) FROM TBL_PLAYLIST) AS PLAYLISTS,
    (SELECT ISNULL(SUM(PLAYS),0) FROM TBL_SONG) AS REPRODUCCIONES;
GO

