PRINT '--- 7. Listado admin de canciones (OFFSET/FETCH) ---';
SELECT s.ID_SONG, s.SONG_NAME, s.SONG_PATH, ISNULL(s.PLAYS,0) AS PLAYS,
    (SELECT COUNT(*) FROM TBL_PLAYER p WHERE p.ID_SONG = s.ID_SONG) AS N_ART,
    (SELECT COUNT(*) FROM TBL_TRACKLIST t WHERE t.ID_SONG = s.ID_SONG) AS N_ALB,
    (SELECT COUNT(*) FROM TBL_PLAYLIST_SONG ps WHERE ps.ID_SONG = s.ID_SONG) AS N_PL
FROM TBL_SONG s
ORDER BY s.ID_SONG DESC
OFFSET 0 ROWS FETCH NEXT 12 ROWS ONLY;
GO

PRINT '--- 8. Listado admin de albumes (OFFSET/FETCH) ---';
