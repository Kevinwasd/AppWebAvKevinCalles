PRINT '--- 19. Comprobacion de la contrasena de ejemplo (SHA-1) ---';
SELECT USERNAME, PASSWORD,
       CASE WHEN UPPER(PASSWORD) = UPPER(CONVERT(varchar(40), HASHBYTES('SHA1', '12345678'), 2))
            THEN 'COINCIDE' ELSE 'TEXTO PLANO U OTRA' END AS ESTADO
FROM TBL_USER;
GO

PRINT '--- 20. Verificacion de la estructura de las tablas ---';
SELECT t.name AS TABLA, c.name AS COLUMNA, ty.name AS TIPO, c.max_length, c.is_nullable
FROM sys.tables t
JOIN sys.columns c ON c.object_id = t.object_id
JOIN sys.types ty ON ty.user_type_id = c.user_type_id
WHERE t.name LIKE 'TBL_%'
ORDER BY t.name, c.column_id;
GO
