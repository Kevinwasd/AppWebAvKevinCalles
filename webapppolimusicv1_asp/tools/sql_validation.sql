GO

PRINT '--- 9. Listado admin de usuarios + conteo de playlists ---';
SELECT u.ID_USER, u.USERNAME, u.EMAIL, u.BIRTHDAY, u.USER_PHOTO, u.USER_TYPE,
    (SELECT COUNT(*) FROM TBL_PLAYLIST pl WHERE pl.ID_USER = u.ID_USER) AS N_PL
FROM TBL_USER u
ORDER BY u.ID_USER ASC
OFFSET 0 ROWS FETCH NEXT 12 ROWS ONLY;
GO

PRINT '--- 10. Listado admin de playlists con busqueda ---';
SELECT pl.ID_PLAYLIST, pl.TITLE, pl.PHOTO, pl.TYPE, pl.CREATION_DATE, u.USERNAME,
    (SELECT COUNT(*) FROM TBL_PLAYLIST_SONG ps WHERE ps.ID_PLAYLIST = pl.ID_PLAYLIST) AS N_SONGS
FROM TBL_PLAYLIST pl INNER JOIN TBL_USER u ON u.ID_USER = pl.ID_USER
WHERE (pl.TITLE LIKE '%a%' OR u.USERNAME LIKE '%a%')
ORDER BY pl.ID_PLAYLIST DESC
OFFSET 0 ROWS FETCH NEXT 12 ROWS ONLY;
GO

PRINT '--- 11. Albumes de un artista ---';
SELECT al.ID_ALBUM, al.TITLE_ALBUM, al.RELEASE_YEAR, al.ALBUM_IMAGE_PATH,
    (SELECT COUNT(*) FROM TBL_TRACKLIST t2 WHERE t2.ID_ALBUM = al.ID_ALBUM) AS N_SONGS
FROM TBL_ALBUM al
WHERE al.ID_ALBUM IN (SELECT DISTINCT t.ID_ALBUM FROM TBL_TRACKLIST t
        WHERE t.ID_SONG IN (SELECT p.ID_SONG FROM TBL_PLAYER p WHERE p.ID_ARTIST = 1))
ORDER BY al.TITLE_ALBUM;
GO

PRINT '--- 12. Selector de playlist (api_playlist_pick) ---';
SELECT pl.ID_PLAYLIST, pl.TITLE, pl.PHOTO, pl.TYPE,
    (SELECT COUNT(*) FROM TBL_PLAYLIST_SONG ps WHERE ps.ID_PLAYLIST = pl.ID_PLAYLIST) AS N_SONGS,
    (SELECT COUNT(*) FROM TBL_PLAYLIST_SONG ps2 WHERE ps2.ID_PLAYLIST = pl.ID_PLAYLIST
      AND ps2.ID_SONG = 1) AS YA_ESTA
FROM TBL_PLAYLIST pl WHERE pl.ID_USER = 1 ORDER BY pl.TITLE;
GO

PRINT '--- 13. Playlists visibles para un usuario (publicas + propias) ---';
SELECT pl.ID_PLAYLIST, pl.TITLE, pl.PHOTO, pl.TYPE, u.USERNAME,
    (SELECT COUNT(*) FROM TBL_PLAYLIST_SONG ps WHERE ps.ID_PLAYLIST = pl.ID_PLAYLIST) AS N_SONGS
FROM TBL_PLAYLIST pl INNER JOIN TBL_USER u ON u.ID_USER = pl.ID_USER
WHERE (pl.TYPE = 0 OR pl.ID_USER = 1)
ORDER BY pl.ID_PLAYLIST DESC;
GO

