PRINT '--- 1. SongListSql (sin WHERE, orden por ID) ---';
SELECT s.ID_SONG, s.SONG_NAME, s.SONG_PATH, ISNULL(s.PLAYS,0) AS PLAYS,
    (SELECT TOP 1 a.ARTIST_NAME + ISNULL(' ' + NULLIF(LTRIM(RTRIM(a.ARTIST_LASTNAME)), ''), '')
       FROM TBL_PLAYER p INNER JOIN TBL_ARTIST a ON a.ID_ARTIST = p.ID_ARTIST
      WHERE p.ID_SONG = s.ID_SONG ORDER BY a.ID_ARTIST) AS ARTIST_NAME,
    (SELECT COUNT(*) FROM TBL_PLAYER p WHERE p.ID_SONG = s.ID_SONG) AS ARTIST_COUNT,
    (SELECT TOP 1 al.ID_ALBUM FROM TBL_TRACKLIST t
       INNER JOIN TBL_ALBUM al ON al.ID_ALBUM = t.ID_ALBUM
      WHERE t.ID_SONG = s.ID_SONG ORDER BY al.ID_ALBUM) AS ID_ALBUM,
    (SELECT TOP 1 al.TITLE_ALBUM FROM TBL_TRACKLIST t
       INNER JOIN TBL_ALBUM al ON al.ID_ALBUM = t.ID_ALBUM
      WHERE t.ID_SONG = s.ID_SONG ORDER BY al.ID_ALBUM) AS ALBUM_TITLE,
    (SELECT TOP 1 al.ALBUM_IMAGE_PATH FROM TBL_TRACKLIST t
       INNER JOIN TBL_ALBUM al ON al.ID_ALBUM = t.ID_ALBUM
      WHERE t.ID_SONG = s.ID_SONG ORDER BY al.ID_ALBUM) AS ALBUM_IMAGE,
    (SELECT TOP 1 a.ARTIST_IMAGE FROM TBL_PLAYER p
       INNER JOIN TBL_ARTIST a ON a.ID_ARTIST = p.ID_ARTIST
      WHERE p.ID_SONG = s.ID_SONG ORDER BY a.ID_ARTIST) AS ARTIST_IMAGE
FROM TBL_SONG s
ORDER BY s.ID_SONG ASC;
GO

PRINT '--- 2. SongListSql paginado (SongPagedWhere, pagina 1, 12 por pagina) ---';
SELECT s.ID_SONG, s.SONG_NAME, s.SONG_PATH, ISNULL(s.PLAYS,0) AS PLAYS,
    (SELECT TOP 1 a.ARTIST_NAME + ISNULL(' ' + NULLIF(LTRIM(RTRIM(a.ARTIST_LASTNAME)), ''), '')
       FROM TBL_PLAYER p INNER JOIN TBL_ARTIST a ON a.ID_ARTIST = p.ID_ARTIST
      WHERE p.ID_SONG = s.ID_SONG ORDER BY a.ID_ARTIST) AS ARTIST_NAME,
    (SELECT COUNT(*) FROM TBL_PLAYER p WHERE p.ID_SONG = s.ID_SONG) AS ARTIST_COUNT,
    (SELECT TOP 1 al.ID_ALBUM FROM TBL_TRACKLIST t
       INNER JOIN TBL_ALBUM al ON al.ID_ALBUM = t.ID_ALBUM
      WHERE t.ID_SONG = s.ID_SONG ORDER BY al.ID_ALBUM) AS ID_ALBUM,
    (SELECT TOP 1 al.TITLE_ALBUM FROM TBL_TRACKLIST t
       INNER JOIN TBL_ALBUM al ON al.ID_ALBUM = t.ID_ALBUM
      WHERE t.ID_SONG = s.ID_SONG ORDER BY al.ID_ALBUM) AS ALBUM_TITLE,
    (SELECT TOP 1 al.ALBUM_IMAGE_PATH FROM TBL_TRACKLIST t
       INNER JOIN TBL_ALBUM al ON al.ID_ALBUM = t.ID_ALBUM
      WHERE t.ID_SONG = s.ID_SONG ORDER BY al.ID_ALBUM) AS ALBUM_IMAGE,
    (SELECT TOP 1 a.ARTIST_IMAGE FROM TBL_PLAYER p
       INNER JOIN TBL_ARTIST a ON a.ID_ARTIST = p.ID_ARTIST
      WHERE p.ID_SONG = s.ID_SONG ORDER BY a.ID_ARTIST) AS ARTIST_IMAGE
FROM TBL_SONG s
WHERE s.ID_SONG IN (SELECT x.ID_SONG FROM (
        SELECT s2.ID_SONG, ROW_NUMBER() OVER (ORDER BY ISNULL(s2.PLAYS,0) DESC, s2.ID_SONG ASC) AS RN
        FROM TBL_SONG s2) x WHERE x.RN BETWEEN 1 AND 12)
ORDER BY ISNULL(s.PLAYS,0) DESC, s.ID_SONG ASC;
GO

